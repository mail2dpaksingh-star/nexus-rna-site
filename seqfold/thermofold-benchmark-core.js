/* NEXUS ThermoFold Benchmark Toolkit 0.2 — independent comparison layer.
   Reference results must be generated by a separate program or curated external source.
   No ViennaRNA source or parameters are included. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;root.NexusFoldBenchmark=api;})(typeof self!=='undefined'?self:globalThis,function(){
'use strict';
const VERSION='0.2.0';
function normalizeSequence(s){return String(s||'').replace(/^>[^\n]*\n/g,'').replace(/\s/g,'').toUpperCase().replace(/T/g,'U');}
function pairs(db){
 const stack=[],found=[];let j=0;
 for(const c of String(db||'')){
  if(c==='(')stack.push(j);else if(c===')'){
   if(!stack.length)throw Error('Unmatched closing parenthesis at '+(j+1));
   found.push([stack.pop()+1,j+1]);
  }else if(c!=='.')throw Error('Unsupported structure symbol: '+c);
  j++;
 }
 if(stack.length)throw Error('Unmatched opening parenthesis');
 return found.sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
}
function pairMetrics(predicted,reference){
 const p=pairs(predicted),r=pairs(reference), pset=new Set(p.map(x=>x.join('-'))),rset=new Set(r.map(x=>x.join('-')));
 let tp=0;for(const id of pset)if(rset.has(id))tp++;
 const fp=p.length-tp,fn=r.length-tp;
 const sensitivity=r.length?tp/r.length:(p.length?0:1);
 const precision=p.length?tp/p.length:(r.length?0:1);
 const f1=precision+sensitivity?2*precision*sensitivity/(precision+sensitivity):0;
 return {tp,fp,fn,predictedPairs:p.length,referencePairs:r.length,precision,sensitivity,f1,exact:predicted===reference};
}
function validateRecord(x){
 if(!x||typeof x!=='object')throw Error('Reference record must be an object');
 const id=String(x.id||'').trim(), seq=normalizeSequence(x.sequence),db=String(x.reference_structure||'').trim();
 if(!id||!/^[\w.-]{1,90}$/.test(id))throw Error('Invalid record ID');
 if(!seq||/[^ACGU]/.test(seq))throw Error(id+': reference sequence must contain only A/C/G/U');
 if(db && db.length!==seq.length)throw Error(id+': reference structure length differs from sequence');
 if(db)pairs(db);
 const en=x.reference_dg===null||x.reference_dg===undefined||x.reference_dg===''?null:Number(x.reference_dg);
 if(en!==null&&!Number.isFinite(en))throw Error(id+': invalid reference ΔG');
 const source=String(x.source||'').trim(),version=String(x.source_version||'').trim(),options=String(x.options||'').trim();
 if((db||en!==null)&&(!source||!version||!options))throw Error(id+': reference predictions require source, source_version and options for reproducibility');
 const kind=String(x.provenance_type||'external_unverified');
 return {id,sequence:seq,reference_structure:db,reference_dg:en,source,source_version:version,options,provenance_type:kind,notes:String(x.notes||'')};
}
function compareRecord(record,pred){
 const r=validateRecord(record);
 if(!pred||pred.sequence!==r.sequence||pred.dotBracket.length!==r.sequence.length)throw Error(r.id+': prediction/sequence mismatch');
 const structure=r.reference_structure?pairMetrics(pred.dotBracket,r.reference_structure):null;
 const diff=r.reference_dg===null?null:pred.deltaG37-r.reference_dg;
 return {id:r.id,sequenceLength:r.sequence.length,gcPercent:100*(r.sequence.match(/[GC]/g)||[]).length/r.sequence.length,
  prediction:{dg:pred.deltaG37,structure:pred.dotBracket,model:pred.model,modelVersion:pred.version},
  reference:{dg:r.reference_dg,structure:r.reference_structure,source:r.source,sourceVersion:r.source_version,options:r.options,provenanceType:r.provenance_type},
  deltaGError:diff,absoluteEnergyError:diff===null?null:Math.abs(diff),...structure?{pairAccuracy:structure}:{pairAccuracy:null},
  warnings:['NEXUS partial energy model and external reference may use different pairing/loop/dangle assumptions; numerical parity is not implied.']};
}
function summarize(rows){
 const dgs=rows.filter(x=>x.deltaGError!==null).map(x=>x.deltaGError),prs=rows.filter(x=>x.pairAccuracy);
 const mean=a=>a.reduce((s,x)=>s+x,0)/a.length;
 const n=dgs.length;
 return {cases:rows.length,withEnergy:n,withStructure:prs.length,
  maeKcalMol:n?mean(dgs.map(Math.abs)):null,rmseKcalMol:n?Math.sqrt(mean(dgs.map(x=>x*x))):null,
  meanBiasKcalMol:n?mean(dgs):null,
  meanPairF1:prs.length?mean(prs.map(x=>x.pairAccuracy.f1)):null,
  exactStructureFraction:prs.length?mean(prs.map(x=>Number(x.pairAccuracy.exact))):null,
  aggregatePrecision:prs.length?prs.reduce((s,x)=>s+x.pairAccuracy.tp,0)/Math.max(1,prs.reduce((s,x)=>s+x.pairAccuracy.predictedPairs,0)):null,
  aggregateSensitivity:prs.length?prs.reduce((s,x)=>s+x.pairAccuracy.tp,0)/Math.max(1,prs.reduce((s,x)=>s+x.pairAccuracy.referencePairs,0)):null,
  caveat:'These are differences between different thermodynamic models, NOT experimental structural accuracy. Accuracy vs observed RNA structures requires curated experimental reference data.'};
}
function parseCSV(s){
 s=String(s||'').replace(/^\uFEFF/,'');const rows=[];let row=[],cell='',quoted=false;
 for(let i=0;i<s.length;i++){const ch=s[i];if(quoted){if(ch==='"'&&s[i+1]==='"'){cell+='"';i++;}else if(ch==='"')quoted=false;else cell+=ch;}
 else if(ch==='"')quoted=true;else if(ch===','){row.push(cell);cell='';}else if(ch==='\n'){row.push(cell.replace(/\r$/,''));rows.push(row);row=[];cell='';}else cell+=ch;}
 if(quoted)throw Error('Unclosed CSV quote');if(cell!==''||row.length){row.push(cell.replace(/\r$/,''));rows.push(row);}if(!rows.length)return [];
 const header=rows.shift().map(x=>x.trim());if(!header.includes('sequence')||!header.includes('id'))throw Error('CSV needs id and sequence columns');
 return rows.filter(r=>r.some(x=>x.trim())).map(r=>validateRecord(Object.fromEntries(header.map((h,i)=>[h,r[i]??'']))));
}
function escapeCSV(v){let s=String(v===null||v===undefined?'':v);if(/^[=+@\-\t\r]/.test(s))s="'"+s;return /[,"\r\n]/.test(s)?'"'+s.replace(/"/g,'""')+'"':s;}
function rowsCSV(rows){const fields=['id','sequenceLength','gcPercent','nexus_dg','reference_dg','dg_error','pair_f1','pair_precision','pair_sensitivity','exact_structure','reference_source','reference_version'];
 return fields.join(',')+'\n'+rows.map(r=>[r.id,r.sequenceLength,r.gcPercent.toFixed(1),r.prediction.dg,r.reference.dg,r.deltaGError,r.pairAccuracy?.f1,r.pairAccuracy?.precision,r.pairAccuracy?.sensitivity,r.pairAccuracy?.exact,r.reference.source,r.reference.sourceVersion].map(escapeCSV).join(',')).join('\n')+'\n';}
return {VERSION,normalizeSequence,pairs,pairMetrics,validateRecord,compareRecord,summarize,parseCSV,rowsCSV};
});
